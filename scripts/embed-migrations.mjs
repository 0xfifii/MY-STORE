// Bundles db/migrations/*.sql into src/lib/migrations.generated.ts so the app can create and
// update its own tables on start-up on any host (including serverless ones like Vercel).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "db", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))} },`).join("\n");
writeFileSync(
  join(root, "src", "lib", "migrations.generated.ts"),
  `// AUTO-GENERATED by scripts/embed-migrations.mjs from db/migrations — do not edit by hand.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`,
);
console.log(`Embedded ${files.length} migrations.`);
